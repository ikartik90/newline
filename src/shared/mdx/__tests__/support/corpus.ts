const awkwardBlocks = AWKWARD.flatMap((value): BlockContent[] => [
  p([text(value)]),
  heading(2, [text(value)]),
  heading(4, [text(value)]),
  p([text(value)], { size: 'sm', color: 'highlight' }),
  quote([text(value)], [text(value)]),
  item(true, [text(value)]),
  item(false, [text(value)]),
  p([text(value)]),
  heading(2, [text(value)], HIGHLIGHT),
  p([text(value)]),
  { type: 'code', lang: null, value }
])

const markedBlocks = MARKS.flatMap((marks): BlockContent[] => [
  ...AWKWARD.map((value) => p([text('before '), text(value, ...marks), text(' after')])),
  ...AWKWARD.map((value) => p([text(value, ...marks)])),
  // Inside a word, and hard against other marks.
  p([text('in'), text('side', ...marks), text('word')]),
  p([text('a', ...marks), text('b', { type: 'underline' }), text('c', ...marks)]),
  heading(3, [text('head '), text('marked', ...marks)])
])

