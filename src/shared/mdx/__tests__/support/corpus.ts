import type { BlockContent, Heading } from 'mdast'
import { writeMdx, type Style } from '../../dialect'
import type { Run, RunMark } from '../../inline'
import { dress, writeInline, writeParagraph } from '../../writing'

// ---------------------------------------------------------------------------
// The notes every reader and writer is tried on: each block and mark the
// dialect has, and text that markdown or a tag would read as something else.
// ---------------------------------------------------------------------------

export const lines = (...rows: string[]): string => rows.join('\n') + '\n'

const text = (value: string, ...marks: RunMark[]): Run =>
  marks.length ? { type: 'text', text: value, marks } : { type: 'text', text: value }

const note = (...blocks: BlockContent[]): string => writeMdx({ type: 'root', children: blocks })

const p = (runs: Run[], style: Style = {}): BlockContent => dress(writeParagraph(runs), style)
const heading = (depth: Heading['depth'], runs: Run[], style: Style = {}): BlockContent =>
  dress({ type: 'heading', depth, children: writeInline(runs, false) }, style)
const quote = (...paragraphs: Run[][]): BlockContent => ({
  type: 'blockquote',
  children: paragraphs.map(writeParagraph).filter((paragraph) => paragraph !== null)
})
const item = (ordered: boolean, runs: Run[]): BlockContent => ({
  type: 'list',
  ordered,
  start: ordered ? 1 : null,
  spread: false,
  children: [{ type: 'listItem', spread: false, children: [writeParagraph(runs)!] }]
})

